const tailwindOxideFallbackSource = `${marker}
const fs = require("node:fs");
const path = require("node:path");

const TEXT_EXTENSIONS = new Set([
  ".astro",
  ".cjs",
  ".css",
  ".cts",
  ".html",
  ".js",
  ".json",
  ".jsx",
  ".md",
  ".mdx",
  ".mjs",
  ".mts",
  ".svelte",
  ".ts",
  ".tsx",
  ".txt",
  ".vue",
]);

const IGNORED_DIRS = new Set([".git", ".hg", ".output", ".vercel", "dist", "build", "coverage", "node_modules"]);
const TOKEN_RE = /[!#%&*@./:[\\\\\\]_a-zA-Z0-9-]+(?:\\([^\\s"'\\\\)]*\\))?/g;

function normalizePath(value) {
  return String(value || "").replace(/\\\\/g, "/");
}

function escapeRegex(value) {
  return value.replace(/[|\\\\{}()[\\]^$+?.]/g, "\\\\$&");
}

function globToRegExp(pattern) {
  const normalized = normalizePath(pattern || "**/*");
  let regex = "^";

  for (let index = 0; index < normalized.length; index += 1) {
    const char = normalized[index];

    if (char === "*") {
      if (normalized[index + 1] === "*") {
        index += 1;

        if (normalized[index + 1] === "/") {
          index += 1;
          regex += "(?:.*\\\\/)?";
        } else {
          regex += ".*";
        }
      } else {
        regex += "[^/]*";
      }

      continue;
    }

    if (char === "?") {
      regex += "[^/]";
      continue;
    }

    if (char === "{") {
      const end = normalized.indexOf("}", index + 1);

      if (end === -1) {
        regex += escapeRegex(char);
        continue;
      }

      const body = normalized.slice(index + 1, end);
      const parts = body.split(",").map((part) => escapeRegex(part));
      regex += "(?:" + parts.join("|") + ")";
      index = end;
      continue;
    }

    regex += escapeRegex(char);
  }

  regex += "$";
  return new RegExp(regex);
}

function looksLikeCandidate(token) {
  if (!token) return false;
  if (token.length > 200) return false;
  if (!/[a-zA-Z]/.test(token)) return false;
  if (token.startsWith("//")) return false;
  if (token.startsWith("http://") || token.startsWith("https://")) return false;
  return true;
}

function extractTokens(content) {
  const candidates = [];
  let match;

  while ((match = TOKEN_RE.exec(content)) !== null) {
    const candidate = match[0];

    if (looksLikeCandidate(candidate)) {
      candidates.push({ candidate, position: match.index });
    }
  }

  return candidates;
}

function isTextFile(filePath) {
  return TEXT_EXTENSIONS.has(path.extname(filePath).toLowerCase());
}

function walk(basePath, relativeDir, patternRe, output) {
  const absoluteDir = relativeDir ? path.join(basePath, relativeDir) : basePath;
  let entries = [];

  try {
    entries = fs.readdirSync(absoluteDir, { withFileTypes: true });
  } catch {
    return;
  }

  for (const entry of entries) {
    const nextRelative = relativeDir ? path.posix.join(relativeDir, entry.name) : entry.name;
    const nextAbsolute = path.join(basePath, nextRelative);

    if (entry.isDirectory()) {
      if (!IGNORED_DIRS.has(entry.name)) {
        walk(basePath, nextRelative, patternRe, output);
      }

      continue;
    }

    if (!entry.isFile() || !isTextFile(nextAbsolute)) {
      continue;
    }

    const normalizedRelative = normalizePath(nextRelative);

    if (patternRe.test(normalizedRelative)) {
      output.add(path.resolve(nextAbsolute));
    }
  }
}

function collectFiles(sources) {
  const included = new Set();
  const excluded = new Set();

  for (const source of sources) {
    const base = path.resolve(source.base || process.cwd());
    const matcher = globToRegExp(source.pattern || "**/*");
    const bucket = source.negated ? excluded : included;
    walk(base, "", matcher, bucket);
  }

  return Array.from(included).filter((filePath) => !excluded.has(filePath)).sort();
}

function readFileContent(filePath) {
  try {
    return fs.readFileSync(filePath, "utf8");
  } catch {
    return "";
  }
}

class Scanner {
  constructor(options = {}) {
    this.normalizedSources = (options.sources || []).map((source) => ({
      base: path.resolve(source.base || process.cwd()),
      pattern: normalizePath(source.pattern || "**/*"),
      negated: Boolean(source.negated),
    }));
    this.globs = this.normalizedSources.filter((source) => !source.negated);
    this.files = collectFiles(this.normalizedSources);
  }

  scan() {
    const tokens = new Set();

    for (const filePath of this.files) {
      for (const match of extractTokens(readFileContent(filePath))) {
        tokens.add(match.candidate);
      }
    }

    return Array.from(tokens);
  }

  scanFiles(input) {
    const tokens = new Set();

    for (const entry of input || []) {
      const content = entry.content ?? (entry.file ? readFileContent(entry.file) : "");

      for (const match of extractTokens(content)) {
        tokens.add(match.candidate);
      }
    }

    return Array.from(tokens);
  }

  getCandidatesWithPositions(input) {
    const candidates = [];

    for (const entry of input || []) {
      const content = entry.content ?? (entry.file ? readFileContent(entry.file) : "");

      for (const match of extractTokens(content)) {
        candidates.push(match);
      }
    }

    return candidates;
  }
}

module.exports = { Scanner };
`;

async function pathExists(path) {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

async function main() {
  let packageJsonPath;

  try {
    packageJsonPath = require.resolve("unenv/package.json");
  } catch {
    console.warn("[repair-unenv] Skipping: unenv is not installed.");
    return;
  }

  const packageRoot = dirname(packageJsonPath);
  const distDir = join(packageRoot, "dist");
  const indexPath = join(distDir, "index.mjs");
  const typesPath = join(distDir, "index.d.mts");

  const unenvIndexExists = await pathExists(indexPath);
  const unenvTypesExists = await pathExists(typesPath);

  if (!unenvIndexExists || !unenvTypesExists) {
    await mkdir(distDir, { recursive: true });

    if (!unenvIndexExists) {
      await writeFile(indexPath, indexSource, "utf8");
    }

    if (!unenvTypesExists) {
      await writeFile(typesPath, typesSource, "utf8");
    }

    console.log("[repair-unenv] Restored missing unenv dist entrypoints.");
  }

  let tailwindOxidePackagePath;

  try {
    tailwindOxidePackagePath = require.resolve("@tailwindcss/oxide/package.json");
  } catch {
    return;
  }

  const tailwindOxideRoot = dirname(tailwindOxidePackagePath);
  const tailwindOxideFallbackPath = join(tailwindOxideRoot, "tailwindcss-oxide.wasi.cjs");

  if (!(await pathExists(tailwindOxideFallbackPath))) {
    await writeFile(tailwindOxideFallbackPath, tailwindOxideFallbackSource, "utf8");
    console.log("[repair-unenv] Added Tailwind oxide WASI fallback shim.");
  }

  let serovalEntryPath;

  try {
    serovalEntryPath = require.resolve("seroval");
  } catch {
    return;
  }

  const serovalRoot = resolve(dirname(serovalEntryPath), "..", "..", "..");
  const serovalBuilds = [
    {
      cjsPath: join(serovalRoot, "dist", "cjs", "production", "index.cjs"),
      esmPath: join(serovalRoot, "dist", "esm", "production", "index.mjs"),
      importPath: "../../cjs/production/index.cjs",
    },
    {
      cjsPath: join(serovalRoot, "dist", "cjs", "development", "index.cjs"),
      esmPath: join(serovalRoot, "dist", "esm", "development", "index.mjs"),
      importPath: "../../cjs/development/index.cjs",
    },
  ];

  for (const build of serovalBuilds) {
    if (await pathExists(build.esmPath)) {
      continue;
    }

    const cjsModule = require(build.cjsPath);
    const exportNames = Object.keys(cjsModule).sort();
    const esmBridge = `${marker}
import cjsModule from "${build.importPath}";

const mod = cjsModule;

export default mod;
${exportNames.map((name) => `export const ${name} = mod.${name};`).join("\n")}
`;

    await mkdir(dirname(build.esmPath), { recursive: true });
    await writeFile(build.esmPath, esmBridge, "utf8");
    console.log(`[repair-unenv] Restored missing seroval ESM bridge: ${build.esmPath}`);
  }
}

await main();
