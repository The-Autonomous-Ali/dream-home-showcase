const marker = "// Generated by scripts/repair-unenv.mjs";

const indexSource = `${marker}
import { resolve as resolvePath } from "node:path";
import { fileURLToPath } from "node:url";

function toArray(value) {
  if (!value) return [];
  return Array.isArray(value) ? value : [value];
}

function mergeRecord(target, source) {
  if (!source || typeof source !== "object") return;

  for (const [key, value] of Object.entries(source)) {
    if (value !== undefined) {
      target[key] = value;
    }
  }
}

function mergeList(target, source) {
  for (const item of toArray(source)) {
    if (item != null && !target.includes(item)) {
      target.push(item);
    }
  }
}

function mergeEnv(target, source = {}) {
  mergeRecord(target.alias, source.alias);
  mergeRecord(target.inject, source.inject);
  mergeList(target.external, source.external);
  mergeList(target.polyfill, source.polyfill);
}

function maybeResolveValue(value, packageRoot) {
  if (Array.isArray(value)) {
    return value.map((entry, index) => (index === 0 ? maybeResolveValue(entry, packageRoot) : entry));
  }

  if (typeof value !== "string") {
    return value;
  }

  if (value.startsWith(".") || value.startsWith("/")) {
    return resolvePath(packageRoot, value);
  }

  return value;
}

function resolveRecord(record, packageRoot) {
  return Object.fromEntries(
    Object.entries(record).map(([key, value]) => [key, maybeResolveValue(value, packageRoot)]),
  );
}

export function defineEnv(options = {}) {
  const { resolve = false, overrides = {}, presets = [] } = options;
  const env = {
    alias: {},
    inject: {},
    external: [],
    polyfill: [],
  };

  for (const preset of toArray(presets)) {
    mergeEnv(env, preset);
  }

  mergeEnv(env, overrides);

  if (resolve) {
    const packageRoot = fileURLToPath(new URL("../", import.meta.url));
    env.alias = resolveRecord(env.alias, packageRoot);
    env.inject = resolveRecord(env.inject, packageRoot);
    env.polyfill = env.polyfill.map((value) => maybeResolveValue(value, packageRoot));
  }

  return { env };
}
`;

